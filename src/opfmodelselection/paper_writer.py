def write_single_paper_model_instance_to_ontology(record, append=True, save=True):
    """Write one checked paper model record into the generated ontology block.

    append=True keeps previous paper model individuals.
    If stable paper metadata matches an existing generated individual, that
    individual is replaced even when hasModelName differs. If only the instance
    name matches but metadata differs, a new unique individual name is created.
    append=False clears the paper-model instance block and writes only this record.
    """
    validate_paper_model_record(record)

    schema_text = BASE_OWL_PATH.read_text(encoding="utf-8")
    assert_core_knowledge_graph_ready_for_paper_write(schema_text)
    if not INSTANCE_OWL_PATH.exists():
        raise FileNotFoundError(
            "Canonical integrated knowledge graph is missing; refusing to "
            f"create a partial replacement: {INSTANCE_OWL_PATH}"
        )
    xml_text = INSTANCE_OWL_PATH.read_text(encoding="utf-8")
    existing_block = get_existing_paper_model_instance_block(xml_text) if append else ""
    instance_name, kept_blocks, replaced_items, duplicate_action = resolve_instance_name_and_existing_blocks(
        existing_block,
        record,
        append=append,
    )
    removed_same_identity = len(replaced_items)
    new_individual_block = build_single_paper_model_individual(record, instance_name=instance_name)
    xml_text = remove_paper_model_instance_block(xml_text)

    individual_blocks = []
    individual_blocks.extend(kept_blocks)
    individual_blocks.append(new_individual_block)

    generated_block = build_paper_model_instance_block(individual_blocks)
    insert_at = xml_text.rfind("</rdf:RDF>")
    if insert_at == -1:
        raise ValueError("Could not find an insertion point in OPF_Knowledge_Graph2.0.owl.")

    xml_text = xml_text[:insert_at] + "\n\n" + generated_block + "\n\n" + xml_text[insert_at:]
    ET.fromstring(xml_text)

    record["written_instance_name"] = instance_name
    record["duplicate_handling_action"] = duplicate_action

    print("模型实例名 / Model instance name:", instance_name)
    print("追加模式 / Append mode:", append)
    print("重复处理动作 / Duplicate handling action:", duplicate_action)
    print("已替换的同论文 metadata 实例数量 / Replaced same-paper-metadata individuals:", removed_same_identity)
    print_replaced_paper_model_report(replaced_items)
    print_paper_model_instance_report(record, instance_name=instance_name, duplicate_action=duplicate_action)

    if save:
        INSTANCE_OWL_PATH.parent.mkdir(parents=True, exist_ok=True)
        INSTANCE_OWL_PATH.write_text(xml_text, encoding="utf-8")
        print("已保存单篇论文模型实例到 / Saved single paper model instance to:", INSTANCE_OWL_PATH)
    return record


def delete_paper_model_instances_from_ontology(instance_names, save=True):
    """Delete existing OPFModel individuals by local instance name.

    Only OPFModel NamedIndividuals are considered. Core ontology classes,
    taxonomy instances, and non-PaperModel individuals are left untouched.
    """
    if isinstance(instance_names, str):
        instance_names = [instance_names]
    names_to_delete = {str(name).strip() for name in instance_names if str(name).strip()}
    if not names_to_delete:
        return {
            "deleted_count": 0,
            "deleted_instances": [],
            "kept_count": 0,
            "saved": False,
        }

    if not INSTANCE_OWL_PATH.exists():
        raise FileNotFoundError(
            "Canonical integrated knowledge graph is missing; refusing to "
            f"create a partial replacement: {INSTANCE_OWL_PATH}"
        )
    xml_text = INSTANCE_OWL_PATH.read_text(encoding="utf-8")
    existing_block = get_existing_paper_model_instance_block(xml_text)
    existing_individuals = parse_existing_paper_model_individuals(existing_block)

    kept_blocks = []
    deleted_items = []
    for item in existing_individuals:
        if item["instance_name"] in names_to_delete:
            deleted_items.append(item)
        else:
            kept_blocks.append(item["block"])

    if not deleted_items:
        return {
            "deleted_count": 0,
            "deleted_instances": [],
            "kept_count": len(existing_individuals),
            "saved": False,
        }

    xml_text = remove_paper_model_instance_block(xml_text)
    generated_block = build_paper_model_instance_block(kept_blocks)
    insert_at = xml_text.rfind("</rdf:RDF>")
    if insert_at == -1:
        raise ValueError("Could not find an insertion point in OPF_Knowledge_Graph2.0.owl.")
    xml_text = xml_text[:insert_at] + "\n\n" + generated_block + "\n\n" + xml_text[insert_at:]
    ET.fromstring(xml_text)

    if save:
        INSTANCE_OWL_PATH.parent.mkdir(parents=True, exist_ok=True)
        INSTANCE_OWL_PATH.write_text(xml_text, encoding="utf-8")

    return {
        "deleted_count": len(deleted_items),
        "deleted_instances": [item["instance_name"] for item in deleted_items],
        "kept_count": len(kept_blocks),
        "saved": bool(save),
    }

