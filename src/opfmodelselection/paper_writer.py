def normalize_identity_value(value):
    if value is None:
        return ""
    return re.sub(r"\s+", " ", str(value).strip()).lower()

def metadata_identity_signature(metadata):
    """Stable metadata signature used for duplicate paper-model detection.

    hasModelName is intentionally excluded. The same paper may be named differently
    by the LLM in different runs, but title/DOI/author/institution should remain stable.
    """
    return tuple(
        normalize_identity_value(metadata.get(key))
        for key in MODEL_IDENTITY_METADATA_KEYS
    )

def metadata_identity_is_usable(signature):
    """Avoid replacing unrelated records when all stable metadata fields are empty."""
    title, year, doi, author, institution = signature
    if doi:
        return True
    if title and (author or institution or year):
        return True
    return False

def same_paper_identity(new_signature, existing_signature):
    """
    Decide whether two paper-model records describe the same paper/model.

    DOI is the strongest identity key: if both DOI values exist and match,
    replace directly even if title/model name/author/institution formatting differs.
    """
    new_title, new_year, new_doi, new_author, new_institution = new_signature
    old_title, old_year, old_doi, old_author, old_institution = existing_signature
    if new_doi and old_doi:
        return new_doi == old_doi
    if not (metadata_identity_is_usable(new_signature) and metadata_identity_is_usable(existing_signature)):
        return False
    return new_signature == existing_signature

def xml_escape(value):
    return (
        str(value)
        .replace("&", "&amp;")
        .replace('"', "&quot;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )

def literal_xml(property_name, value):
    if value is None or value == "":
        return None
    xsd_type = MODEL_DATA_PROPERTY_TYPES.get(property_name, "string")
    if xsd_type == "boolean":
        value = "true" if bool(value) else "false"
    return f'  <{property_name} rdf:datatype="http://www.w3.org/2001/XMLSchema#{xsd_type}">{xml_escape(value)}</{property_name}>'

def opf_full_iri(local_name):
    """Return the full OPF ontology IRI for a local class or individual name."""
    if not local_name:
        return ""
    value = str(local_name)
    if value.startswith("http://") or value.startswith("https://"):
        return value
    if value.startswith("#"):
        value = value[1:]
    return OPF_IRI + value

def object_assertion_xml(property_name, target_class_name):
    return f'  <{property_name} rdf:resource="{xml_escape(opf_full_iri(target_class_name))}"/>'

def oeo_object_assertion_xml(oeo_property_local_name, target_class_name):
    return f'  <oeo:{oeo_property_local_name} rdf:resource="{xml_escape(opf_full_iri(target_class_name))}"/>'

def build_single_paper_model_individual(record, instance_name=None):
    data_properties = build_model_data_properties(record)
    structure = record["structure"]
    features = record["features"]
    instance_name = instance_name or get_record_instance_name(record)

    lines = [
        f'<owl:NamedIndividual rdf:about="{xml_escape(opf_full_iri(instance_name))}">',
        f'  <rdf:type rdf:resource="{xml_escape(opf_full_iri("OPFModel"))}"/>',
    ]

    for property_name, value in data_properties.items():
        literal_line = literal_xml(property_name, value)
        if literal_line:
            lines.append(literal_line)

    for property_name, xml_tag in OPF_OBJECT_PROPERTY_TO_XML_TAG.items():
        for class_name in features.get(property_name, []) or []:
            lines.append(object_assertion_xml(xml_tag, class_name))
    for class_name in features.get("coversSector", []) or []:
        lines.append(oeo_object_assertion_xml(OEO_COVERS_SECTOR_XML_TAG, class_name))

    for class_name in structure.get("objectiveLevel1", []):
        lines.append(object_assertion_xml("hasObjectiveFunction", class_name))
    for class_name in structure.get("objectiveLevel2", []):
        lines.append(object_assertion_xml("hasObjectiveFunction", class_name))
    for class_name in structure.get("constraintLevel1", []):
        lines.append(object_assertion_xml("hasConstraintFunction", class_name))
    for class_name in structure.get("constraintLevel2", []):
        lines.append(object_assertion_xml("hasConstraintFunction", class_name))
    for class_name in structure.get("parameterLevel1", []):
        lines.append(object_assertion_xml("usesParameter", class_name))
    for class_name in structure.get("parameterLevel2", []):
        lines.append(object_assertion_xml("usesParameter", class_name))

    lines.append("</owl:NamedIndividual>")
    return "\n".join(lines)

def infer_missing_level1_from_level2(selected_level1, selected_level2, level2_by_level1):
    """
    If a level-2 taxonomy class is selected, its level-1 parent can be inferred from the ontology tree.
    """
    if "unique_preserve_order" in globals():
        dedupe = unique_preserve_order
    else:
        def dedupe(items):
            seen = set()
            result = []
            for item in items or []:
                if item and item not in seen:
                    seen.add(item)
                    result.append(item)
            return result

    selected_level1 = dedupe(selected_level1 or [])
    selected_level2 = dedupe(selected_level2 or [])
    parent_by_level2 = {}
    for level1, children in level2_by_level1.items():
        for child in children:
            parent_by_level2.setdefault(child, level1)

    added_parents = []
    for child in selected_level2:
        parent = parent_by_level2.get(child)
        if parent and parent not in selected_level1:
            selected_level1.append(parent)
            added_parents.append(parent)

    return dedupe(selected_level1), dedupe(added_parents)

def complete_structure_level1_from_level2(record):
    """
    Repair missing level-1 selections before final validation and OWL writing.
    """
    structure = record.setdefault("structure", {})
    repair_specs = [
        ("objectiveLevel1", "objectiveLevel2", OBJECTIVE_LEVEL2_BY_LEVEL1, "目标函数 / Objective"),
        ("constraintLevel1", "constraintLevel2", CONSTRAINT_LEVEL2_BY_LEVEL1, "约束函数 / Constraint"),
        ("parameterLevel1", "parameterLevel2", PARAMETER_LEVEL2_BY_LEVEL1, "参数变量 / Parameter"),
    ]
    repair_report = {}
    for level1_key, level2_key, mapping, label in repair_specs:
        repaired_level1, added = infer_missing_level1_from_level2(
            structure.get(level1_key, []),
            structure.get(level2_key, []),
            mapping,
        )
        structure[level1_key] = repaired_level1
        structure[level2_key] = list(structure.get(level2_key, []) or [])
        repair_report[level1_key] = added
        if added:
            print(f"自动补齐 {label} 一级类 / Auto-added level-1 classes: {added}")
    record["structure"] = structure
    return repair_report

def validate_paper_model_record(record):
    """Validate LLM outputs against ontology whitelists before writing."""
    normalize_record_for_new_papermodel_schema(record)
    metadata = record["metadata"]
    if not metadata.get("hasModelName"):
        raise ValueError(f"Missing hasModelName for {record.get('source_id')}")
    if is_empty_metadata_value(metadata.get("hasPaperTitle")):
        raise ValueError(
            "Missing hasPaperTitle before ontology write. "
            "The record must contain a paper title or a source PDF path that can provide a title candidate."
        )

    complete_structure_level1_from_level2(record)
    structure = record["structure"]
    for class_name in structure.get("objectiveLevel1", []):
        if class_name not in OBJECTIVE_LEVEL1_CLASSES:
            raise ValueError(f"Invalid objective level-1 class: {class_name}")
    for class_name in structure.get("objectiveLevel2", []):
        if class_name not in OBJECTIVE_LEVEL2_CLASSES:
            raise ValueError(f"Invalid objective level-2 class: {class_name}")
    for class_name in structure.get("constraintLevel1", []):
        if class_name not in CONSTRAINT_LEVEL1_CLASSES:
            raise ValueError(f"Invalid constraint level-1 class: {class_name}")
    for class_name in structure.get("constraintLevel2", []):
        if class_name not in CONSTRAINT_LEVEL2_CLASSES:
            raise ValueError(f"Invalid constraint level-2 class: {class_name}")
    for class_name in structure.get("parameterLevel1", []):
        if class_name not in PARAMETER_LEVEL1_CLASSES:
            raise ValueError(f"Invalid parameter level-1 class: {class_name}")
    for class_name in structure.get("parameterLevel2", []):
        if class_name not in PARAMETER_LEVEL2_CLASSES:
            raise ValueError(f"Invalid parameter level-2 class: {class_name}")

    validate_level2_under_selected_level1(
        structure.get("objectiveLevel1", []),
        structure.get("objectiveLevel2", []),
        OBJECTIVE_LEVEL2_BY_LEVEL1,
        "Objective",
    )
    validate_level2_under_selected_level1(
        structure.get("constraintLevel1", []),
        structure.get("constraintLevel2", []),
        CONSTRAINT_LEVEL2_BY_LEVEL1,
        "Constraint",
    )
    validate_level2_under_selected_level1(
        structure.get("parameterLevel1", []),
        structure.get("parameterLevel2", []),
        PARAMETER_LEVEL2_BY_LEVEL1,
        "Parameter",
    )

    for property_name, selected_classes in record["features"].items():
        allowed = set(FEATURE_ALLOWED_CLASSES_BY_PROPERTY[property_name])
        for class_name in selected_classes:
            if class_name not in allowed:
                raise ValueError(f"Invalid feature class for {property_name}: {class_name}")

def local_name_from_opf_individual_iri(iri):
    """Return local name for #Name or full OPF IRI + Name."""
    if not iri:
        return ""
    if iri.startswith("#"):
        return iri[1:]
    if iri.startswith(OPF_IRI):
        return iri[len(OPF_IRI):]
    return iri

def is_opf_model_individual_block(block):
    """Accept both old #OPFModel and new full OPF IRI rdf:type forms."""
    return (
        '<rdf:type rdf:resource="#OPFModel"/>' in block
        or f'<rdf:type rdf:resource="{OPF_IRI}OPFModel"/>' in block
    )

def extract_existing_paper_model_individual_blocks(xml_text):
    """
    Extract only OPFModel individuals, independent of generated block markers.

    Supports both old rdf:about="#Name" and new full OPF IRI rdf:about forms.
    """
    pattern = re.compile(
        r'<owl:NamedIndividual rdf:about="([^"]+)">.*?</owl:NamedIndividual>',
        re.DOTALL,
    )
    blocks = []
    for match in pattern.finditer(xml_text or ""):
        block = match.group(0)
        if is_opf_model_individual_block(block):
            blocks.append(block)
    return blocks

def get_existing_paper_model_instance_block(xml_text):
    return "\n".join(extract_existing_paper_model_individual_blocks(xml_text)).strip()

def remove_paper_model_instance_block(xml_text):
    """
    Remove only generated paper-instance markers/header and OPFModel individuals.

    Never remove the whole BEGIN..END span, because that span may contain core
    taxonomy blocks in older malformed files.
    """
    header_pattern = re.compile(
        re.escape(PAPER_MODEL_INSTANCE_BEGIN_MARKER)
        + r"\s*<!--\s*Generated OPFModel individuals extracted from papers by the two-pass LLM workflow\."
        + r".*?hasModelName is deliberately ignored for duplicate detection because it is LLM-generated and unstable\.\s*-->\s*",
        re.DOTALL,
    )
    xml_text = header_pattern.sub("", xml_text)
    xml_text = xml_text.replace(PAPER_MODEL_INSTANCE_BEGIN_MARKER, "")
    xml_text = xml_text.replace(PAPER_MODEL_INSTANCE_END_MARKER, "")

    for block in extract_existing_paper_model_individual_blocks(xml_text):
        xml_text = xml_text.replace(block, "")

    return xml_text

def extract_literal_from_individual_block(individual_block, property_name):
    pattern = re.compile(
        rf"<{re.escape(property_name)}[^>]*>(.*?)</{re.escape(property_name)}>",
        re.DOTALL,
    )
    match = pattern.search(individual_block)
    if not match:
        return None
    return (
        match.group(1)
        .replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", '"')
        .replace("&amp;", "&")
        .strip()
    )

def parse_existing_paper_model_individuals(block_text):
    """Read paper-model individuals from generated block text or full OWL fragments."""
    pattern = re.compile(
        r'<owl:NamedIndividual rdf:about="([^"]+)">.*?</owl:NamedIndividual>',
        re.DOTALL,
    )
    individuals = []
    for match in pattern.finditer(block_text or ""):
        individual_block = match.group(0)
        if not is_opf_model_individual_block(individual_block):
            continue
        metadata = {
            key: extract_literal_from_individual_block(individual_block, key)
            for key in MODEL_IDENTITY_METADATA_KEYS
        }
        individuals.append({
            "instance_name": local_name_from_opf_individual_iri(match.group(1)),
            "block": individual_block,
            "metadata": metadata,
            "identity_signature": metadata_identity_signature(metadata),
        })
    return individuals

def make_unique_instance_name(base_name, existing_names, record):
    """Create a stable unique name when the model name is reused by another paper."""
    metadata = record.get("metadata", {})
    suffix_parts = [
        metadata.get("hasPublicationYear"),
        sanitize_owl_local_name(metadata.get("hasPaperTitle") or record.get("source_id"), fallback="Paper"),
    ]
    suffix = "_".join(str(part) for part in suffix_parts if part)
    candidate = sanitize_owl_local_name(f"{base_name}_{suffix}", fallback=base_name)
    if candidate not in existing_names:
        return candidate
    counter = 2
    while f"{candidate}_{counter}" in existing_names:
        counter += 1
    return f"{candidate}_{counter}"

def resolve_instance_name_and_existing_blocks(existing_block, record, append=True):
    """Decide whether to replace an existing individual or create a new one.

    Same DOI or stable paper metadata -> replace, even if hasModelName differs.
    Same instance name but different paper metadata -> create a unique new instance name.
    """
    if not append:
        return get_record_instance_name(record), [], [], "clear_block_write_current_only"

    base_name = get_record_instance_name(record)
    new_signature = metadata_identity_signature(record.get("metadata", {}))
    existing_individuals = parse_existing_paper_model_individuals(existing_block)
    existing_names = {item["instance_name"] for item in existing_individuals}

    kept_blocks = []
    replaced_items = []
    action = "append_new_paper_metadata"
    final_name = base_name

    for item in existing_individuals:
        same_metadata = same_paper_identity(new_signature, item["identity_signature"])
        if same_metadata:
            replaced_items.append(item)
            action = "replace_same_paper_metadata_modelname_ignored"
            continue
        kept_blocks.append(item["block"])

    if not replaced_items and base_name in existing_names:
        final_name = make_unique_instance_name(base_name, existing_names, record)
        action = "same_instance_name_but_different_metadata_create_new_instance"

    return final_name, kept_blocks, replaced_items, action

def build_paper_model_instance_block(individual_blocks):
    lines = [
        PAPER_MODEL_INSTANCE_BEGIN_MARKER,
        "<!--",
        "Generated OPFModel individuals extracted from papers by the two-pass LLM workflow.",
        "Each single-paper write appends a checked model or replaces an existing individual with the same stable paper metadata.",
        "hasModelName is deliberately ignored for duplicate detection because it is LLM-generated and unstable.",
        "-->",
    ]
    for block in individual_blocks:
        if block and block.strip():
            lines.append(block.strip())
    lines.append(PAPER_MODEL_INSTANCE_END_MARKER)
    return "\n".join(lines)


