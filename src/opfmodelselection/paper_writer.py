def _write_guard_resource_to_local_or_iri(resource):
    if not resource:
        return None
    if resource.startswith("#"):
        return resource[1:]
    if resource.startswith(OPF_IRI):
        return resource[len(OPF_IRI):]
    return resource

def _write_guard_class_parent_map(xml_text):
    root = ET.fromstring(xml_text)
    rdf_about = "{http://www.w3.org/1999/02/22-rdf-syntax-ns#}about"
    rdf_resource = "{http://www.w3.org/1999/02/22-rdf-syntax-ns#}resource"
    owl_class = "{http://www.w3.org/2002/07/owl#}Class"
    rdfs_subclass = "{http://www.w3.org/2000/01/rdf-schema#}subClassOf"
    parent_map = {}
    for elem in root.findall(f".//{owl_class}"):
        class_name = _write_guard_resource_to_local_or_iri(elem.get(rdf_about))
        if not class_name or class_name.startswith("http://") or class_name.startswith("https://"):
            continue
        parents = []
        for sub in elem.findall(rdfs_subclass):
            parent = _write_guard_resource_to_local_or_iri(sub.get(rdf_resource))
            if parent:
                parents.append(parent)
        parent_map[class_name] = parents
    return parent_map

def _write_guard_property_names(xml_text):
    root = ET.fromstring(xml_text)
    rdf_about = "{http://www.w3.org/1999/02/22-rdf-syntax-ns#}about"
    property_names = set()
    for tag in [
        "{http://www.w3.org/2002/07/owl#}DatatypeProperty",
        "{http://www.w3.org/2002/07/owl#}ObjectProperty",
    ]:
        for elem in root.findall(f".//{tag}"):
            name = _write_guard_resource_to_local_or_iri(elem.get(rdf_about))
            if name:
                property_names.add(name)
    return property_names

def assert_core_knowledge_graph_ready_for_paper_write(xml_text):
    """
    Refuse to write paper-model instances if the real base ontology structure is missing.
    This check no longer requires old generated-block markers, because the OWL may be manually curated.
    """
    missing_schema_markers = [
        marker
        for marker in CORE_REQUIRED_MARKERS_FOR_PAPER_WRITE
        if marker not in xml_text
    ]
    if missing_schema_markers:
        raise RuntimeError(
            "OPF_Ontology2.0.owl 缺少 OPFModel schema 区块，无法确认 PaperModel 属性定义。"
            "\nMissing schema markers: " + ", ".join(missing_schema_markers)
        )

    parent_map = _write_guard_class_parent_map(xml_text)
    missing_parent_relations = []
    for class_name, parent_resource in CORE_REQUIRED_PARENT_CHECKS_FOR_PAPER_WRITE:
        parents = parent_map.get(class_name, [])
        if parent_resource not in parents:
            missing_parent_relations.append(f"{class_name} -> {parent_resource}; actual={parents}")

    if missing_parent_relations:
        raise RuntimeError(
            "OPF_Ontology2.0.owl 的核心父子类关系不完整，暂不写入论文实例。"
            "\nMissing parent relations: " + "; ".join(missing_parent_relations)
        )

    property_names = _write_guard_property_names(xml_text)
    missing_properties = [
        prop for prop in CORE_REQUIRED_SCHEMA_PROPERTIES_FOR_PAPER_WRITE
        if prop not in property_names
    ]
    if missing_properties:
        raise RuntimeError(
            "OPF_Ontology2.0.owl 缺少 PaperModel / OPFModel 属性定义，暂不写入论文实例。"
            "\nMissing properties: " + ", ".join(missing_properties)
        )

    return True


