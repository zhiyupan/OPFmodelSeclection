def normalize_search_text(value):
    """Normalize text for fuzzy local filename matching."""
    return re.sub(r"[^a-z0-9]+", " ", str(value or "").lower()).strip()

def score_paper_file_against_metadata(path, metadata):
    """Score a local paper file against replaced metadata."""
    stem = normalize_search_text(Path(path).stem)
    title = normalize_search_text(metadata.get("hasPaperTitle"))
    doi = normalize_search_text(metadata.get("hasDOI"))
    model_name = normalize_search_text(metadata.get("hasModelName"))
    score = 0

    if title:
        title_tokens = [token for token in title.split() if len(token) > 2]
        if title_tokens:
            matched = sum(1 for token in title_tokens if token in stem)
            score += matched / len(title_tokens) * 100

    if model_name:
        model_tokens = [token for token in model_name.split() if len(token) > 2]
        if model_tokens:
            matched = sum(1 for token in model_tokens if token in stem)
            score += matched / len(model_tokens) * 30

    if doi and doi.replace(" ", "") in stem.replace(" ", ""):
        score += 150

    return score

def find_replaced_paper_paths(metadata, top_k=3):
    """
    Search the source-paper input directory for a replaced model's likely file.
    """
    paper_dir = PAPER_DIR
    if not paper_dir.exists():
        return []
    candidates = []
    for suffix in ("*.pdf", "*.txt", "*.md"):
        candidates.extend(paper_dir.rglob(suffix))
    scored = [
        (score_paper_file_against_metadata(path, metadata), path)
        for path in candidates
    ]
    scored = [(score, path) for score, path in scored if score > 0]
    scored.sort(key=lambda item: item[0], reverse=True)
    return [str(path) for score, path in scored[:top_k]]

